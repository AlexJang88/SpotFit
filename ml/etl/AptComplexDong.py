# K-apt 서울 단지(MapComplex.py 결과) → 아파트 매매 모델용 행정동별 단지 항목 → data/processed/행정동별_단지정보.csv
#  아파트·주상복합 단지만 셈 (연립주택·다세대·도시형 생활주택은 제외). 단지가 하나도 없는 행정동은 모델 쪽에서 빈 값으로 둠
#  대형 건설사 = 10대 건설사 계열(삼성물산·현대건설·대우건설·GS건설·대림산업(DL)·포스코·롯데건설·SK·현대산업개발(HDC)·현대엔지니어링). 시공사 이름에 포함되면 대형으로 봄 (제 기준이며, 옛 이름 삼성건설·LG건설·럭키 포함)
import os
import numpy as np, pandas as pd

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'data') + os.sep
BIG = ['삼성물산', '삼성건설', '현대건설', '대우건설', 'GS건설', 'LG건설', '럭키', '대림산업', '대림건설', 'DL', '포스코', '롯데건설', 'SK건설', 'SK에코', '현대산업개발', 'HDC', '현대엔지니어링']

c = pd.read_csv(DATA + 'interim/기타/단지_행정동.csv', encoding='utf-8-sig', low_memory=False)
n0 = len(c)
c = c[c['단지분류'].isin(['아파트', '주상복합'])].dropna(subset=['행정동_코드']).copy()
c['세대수'] = c['세대수'].astype(float)
c = c[c['세대수'] > 0]                                                             # 세대수 0인 단지 제외
c['대단지'] = c['세대수'] >= 1000
c['대형건설사'] = c['시공사'].fillna('').apply(lambda s: any(b in s for b in BIG))
c['계단식'] = c['복도유형'] == '계단식'
c['최고층수'] = c['최고층수'].where(c['최고층수'] > 0)                                  # 최고층수 0은 입력 안 된 값으로 보고 빈 값 처리
c['임대세대수'] = c['임대세대수'].fillna(0).clip(upper=c['세대수'])                 # 임대가 세대수보다 큰 입력 오류는 세대수로 맞춤
print(f'단지 {n0:,}개 → 아파트·주상복합, 세대수>0 인 {len(c):,}개 | 대형 건설사 {c["대형건설사"].mean() * 100:.1f}%')
num = lambda col: pd.to_numeric(c[col], errors='coerce')
c['연식'] = 2026 - num('사용승인일') // 10000
c['신축'] = c['연식'] <= 10
c['노후30'] = c['연식'] >= 30
c['지역난방'] = c['난방방식'] == '지역난방'
c['분양'] = c['분양형태'] == '분양'
c['지하주차비율'] = np.where(num('총주차대수') > 0, num('지하주차대수') / num('총주차대수'), np.nan)
c['세대당 승강기'] = (num('승강기(승객용)') + num('승강기(승객+화물)')) / c['세대수']
c['세대당 충전기'] = (num('전기차 충전시설 설치대수(지하)').fillna(0) + num('전기차 충전시설 설치대수(지상)').fillna(0)) / c['세대수']
c['세대당 CCTV'] = num('CCTV대수') / c['세대수']
c['홈네트워크'] = c['홈네트워크'] == '유'
c['경비 인원'] = num('경비관리-인원') / c['세대수'] * 100
c['자치관리'] = c['관리방식'].fillna('').str.startswith('자치')
c['운동시설'] = c['주민운동시설'].notna()
c['철골'] = c['건물구조'].fillna('').str.contains('철골')
cnt = lambda col: c[col].where(c[col].notna()).astype('string').str.split(',').map(lambda x: len(x) if isinstance(x, list) else np.nan)      # 쉼표로 나열된 시설 개수 (빈 값은 모름으로 둠)
c['부대복리시설 수'] = cnt('부대복리시설')
c['단지기타시설 수'] = cnt('단지기타시설')
c['신재생에너지'] = c['신재생 에너지 시설'].notna()                                                    # 빈 값은 '없음'으로 봄 (77%가 비어 있음)
c['세대당 차량보유'] = num('차량보유대수(전체)') / c['세대수']
c['충전기설치'] = (c['전기충전기설치여부(지상)'] == '설치') | (c['전기충전기설치여부(지하)'] == '설치')
g = c.groupby('행정동_코드')
t = pd.DataFrame({
    '아파트 단지 수(K-apt)': g.size(),
    '단지 평균 세대수': g['세대수'].mean(),
    '대단지(1000세대+) 비율(%)': g['대단지'].mean() * 100,
    '세대당 주차대수': g['총주차대수'].sum() / g['세대수'].sum(),
    '계단식 비율(%)': g['계단식'].mean() * 100,
    '임대세대 비율(%)': g['임대세대수'].sum() / g['세대수'].sum() * 100,
    '대형 건설사 단지 비율(%)': g['대형건설사'].mean() * 100,
    '단지 평균 최고층수': g['최고층수'].mean(),
    '단지 평균 연식(년)': g['연식'].mean(),
    '신축(10년 이내) 단지 비율(%)': g['신축'].mean() * 100,
    '30년 이상 단지 비율(%)': g['노후30'].mean() * 100,
    '지역난방 단지 비율(%)': g['지역난방'].mean() * 100,
    '분양 단지 비율(%)': g['분양'].mean() * 100,
    '지하주차 비율': g['지하주차비율'].mean(),
    '세대당 승강기 수': g['세대당 승강기'].mean(),
    '세대당 전기차충전기 수': g['세대당 충전기'].mean(),
    '단지 내 세대당 CCTV 수': g['세대당 CCTV'].mean(),
    '홈네트워크 단지 비율(%)': g['홈네트워크'].mean() * 100,
    '100세대당 경비 인원': g['경비 인원'].mean(),
    '자치관리 단지 비율(%)': g['자치관리'].mean() * 100,
    '주민운동시설 단지 비율(%)': g['운동시설'].mean() * 100,
    '철골 구조 단지 비율(%)': g['철골'].mean() * 100,
    '단지 평균 동수': g['동수'].mean(),
    '동네 총 세대수(K-apt)': g['세대수'].sum(),
    '가장 큰 단지 세대수': g['세대수'].max(),
    '단지 평균 부대복리시설 수': g['부대복리시설 수'].mean(),
    '단지 평균 단지기타시설 수': g['단지기타시설 수'].mean(),
    '신재생에너지 단지 비율(%)': g['신재생에너지'].mean() * 100,
    '세대당 차량보유대수': g['세대당 차량보유'].mean(),
    '전기충전기 설치 단지 비율(%)': g['충전기설치'].mean() * 100,
}).reset_index()
t.round(3).to_csv(DATA + 'processed/행정동별_단지정보.csv', index=False, encoding='utf-8-sig')
print(f'행정동 {len(t)}곳 | 저장: {os.path.abspath(DATA + "processed/행정동별_단지정보.csv")}')
print(t.drop(columns='행정동_코드').describe().round(1).T[['count', 'min', '50%', 'max']].to_string())
