CREATE FUNCTION spotfit.guard_active_deployment() RETURNS trigger LANGUAGE plpgsql
SET search_path = spotfit, public, pg_catalog AS $$
DECLARE m ml_model_version; total numeric; n integer;
BEGIN
 IF NEW.status<>'ACTIVE' THEN RETURN NEW; END IF;
 SELECT * INTO STRICT m FROM ml_model_version WHERE model_version_id=NEW.model_version_id FOR UPDATE;
 IF m.status<>'VALIDATED' OR NOT m.validation_passed OR NOT m.is_champion OR NOT EXISTS (
  SELECT 1 FROM ml_training_run t JOIN feature_dataset_version f USING(feature_dataset_id)
  WHERE t.training_run_id=m.training_run_id AND t.status='SUCCEEDED' AND f.quality_passed
 ) OR NOT EXISTS (SELECT 1 FROM ml_model_metric WHERE model_version_id=m.model_version_id AND dataset_split IN ('CV','HOLDOUT','TEST')) THEN
  RAISE EXCEPTION 'Deployment needs validated champion, successful training, quality-passed data and evaluation metrics' USING ERRCODE='23514';
 END IF;
 IF EXISTS (SELECT 1 FROM ml_model_deployment d JOIN ml_model_version v USING(model_version_id)
  WHERE d.environment=NEW.environment AND d.status='ACTIVE' AND v.model_type=m.model_type
   AND v.prediction_horizon=m.prediction_horizon AND d.deployment_id<>NEW.deployment_id) THEN
  RAISE EXCEPTION 'Retire the previous deployment for this type/horizon first' USING ERRCODE='23514';
 END IF;
 SELECT count(weight_pct),sum(weight_pct) INTO n,total FROM ml_model_feature WHERE model_version_id=m.model_version_id;
 IF n>0 AND abs(total-100)>0.000001 THEN
  RAISE EXCEPTION 'Scored feature weights must sum to 100 percent' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER deployment_gate BEFORE INSERT OR UPDATE ON spotfit.ml_model_deployment
FOR EACH ROW EXECUTE FUNCTION spotfit.guard_active_deployment();

CREATE FUNCTION spotfit.guard_prediction() RETURNS trigger LANGUAGE plpgsql
SET search_path = spotfit, public, pg_catalog AS $$
DECLARE m ml_model_version; a ref_admin_area;
BEGIN
 SELECT * INTO STRICT m FROM ml_model_version WHERE model_version_id=NEW.model_version_id;
 SELECT * INTO STRICT a FROM ref_admin_area WHERE area_id=NEW.area_id;
 IF TG_TABLE_NAME='service_safety_prediction' THEN
  IF a.area_level<>'DISTRICT' OR m.model_type<>NEW.safety_domain
    OR (NEW.prediction_kind='FORECAST' AND NEW.prediction_year-NEW.reference_year<>m.prediction_horizon) THEN
   RAISE EXCEPTION 'Safety prediction domain, district or horizon mismatch' USING ERRCODE='23514';
  END IF;
 ELSE
  IF a.area_level<>'DONG' OR m.model_type<>(CASE NEW.transaction_type WHEN 'SALE' THEN 'APARTMENT_SALE' WHEN 'JEONSE' THEN 'APARTMENT_JEONSE' ELSE 'APARTMENT_MONTHLY_RENT' END) THEN
   RAISE EXCEPTION 'Property prediction model/domain/area mismatch' USING ERRCODE='23514';
  END IF;
  IF NEW.apartment_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM core_apartment WHERE apartment_id=NEW.apartment_id AND area_id=NEW.area_id) THEN
   RAISE EXCEPTION 'Apartment and prediction area differ' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;
