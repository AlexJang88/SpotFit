CREATE TABLE spotfit.ref_admin_area (
    area_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_code varchar(10) NOT NULL,
    area_name text NOT NULL,
    area_level text NOT NULL CHECK (area_level IN ('CITY','DISTRICT','DONG')),
    parent_area_id bigint REFERENCES spotfit.ref_admin_area,
    valid_from date NOT NULL,
    valid_to date,
    is_current boolean NOT NULL DEFAULT true,
    boundary geometry(MultiPolygon,4326),
    code_system text NOT NULL DEFAULT 'MOIS',
    source_snapshot text,
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    CHECK (is_current = (valid_to IS NULL)),
    CHECK (parent_area_id IS DISTINCT FROM area_id),
    CHECK ((area_level='CITY' AND area_code ~ '^[0-9]{2}$' AND parent_area_id IS NULL)
        OR (area_level='DISTRICT' AND area_code ~ '^[0-9]{5}$' AND parent_area_id IS NOT NULL)
        OR (area_level='DONG' AND area_code ~ '^[0-9]{10}$' AND parent_area_id IS NOT NULL)),
    CHECK (boundary IS NULL OR (NOT ST_IsEmpty(boundary) AND ST_IsValid(boundary))),
    UNIQUE(code_system,area_code,valid_from),
    EXCLUDE USING gist (code_system WITH =, area_code WITH =, daterange(valid_from,valid_to,'[)') WITH &&)
);
