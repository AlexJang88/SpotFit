CREATE FUNCTION spotfit.guard_used_features() RETURNS trigger LANGUAGE plpgsql
SET search_path = spotfit, public, pg_catalog AS $$
DECLARE ids bigint[];
BEGIN
 IF TG_OP='INSERT' THEN ids:=ARRAY[NEW.model_version_id];
 ELSIF TG_OP='DELETE' THEN ids:=ARRAY[OLD.model_version_id];
 ELSE ids:=ARRAY[OLD.model_version_id,NEW.model_version_id]; END IF;
 IF EXISTS (SELECT 1 FROM ml_model_deployment WHERE model_version_id=ANY(ids) AND status IN ('ACTIVE','RETIRED'))
 OR EXISTS (SELECT 1 FROM service_safety_prediction WHERE model_version_id=ANY(ids))
 OR EXISTS (SELECT 1 FROM service_property_prediction WHERE model_version_id=ANY(ids)) THEN
  RAISE EXCEPTION 'Features of a deployed/predicted model are immutable; create a new model version' USING ERRCODE='23514';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
CREATE TRIGGER used_features_guard BEFORE INSERT OR UPDATE OR DELETE ON spotfit.ml_model_feature
FOR EACH ROW EXECUTE FUNCTION spotfit.guard_used_features();

