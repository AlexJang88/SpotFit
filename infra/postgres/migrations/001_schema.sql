-- Index every referencing FK (not just the frequently queried ones).
DO $$
DECLARE r record;
BEGIN
 FOR r IN
  SELECT c.conrelid::regclass AS relation, c.oid, string_agg(quote_ident(a.attname),',' ORDER BY u.ordinality) AS columns
  FROM pg_constraint c CROSS JOIN LATERAL unnest(c.conkey) WITH ORDINALITY u(attnum,ordinality)
  JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=u.attnum
  WHERE c.contype='f' AND c.connamespace='spotfit'::regnamespace
  GROUP BY c.conrelid,c.oid
 LOOP
  EXECUTE format('CREATE INDEX %I ON %s (%s)', 'fk_'||r.oid, r.relation,r.columns);
 END LOOP;
END $$;

CREATE FUNCTION spotfit.guard_area_hierarchy() RETURNS trigger LANGUAGE plpgsql
SET search_path = spotfit, public, pg_catalog AS $$
DECLARE p ref_admin_area;
BEGIN
 PERFORM pg_advisory_xact_lock(718261117);
 IF NEW.parent_area_id IS NOT NULL THEN
  SELECT * INTO STRICT p FROM ref_admin_area WHERE area_id=NEW.parent_area_id;
  IF NOT ((NEW.area_level='DISTRICT' AND p.area_level='CITY') OR (NEW.area_level='DONG' AND p.area_level='DISTRICT'))
     OR NEW.code_system<>p.code_system OR NEW.area_code NOT LIKE p.area_code||'%' THEN
   RAISE EXCEPTION 'Invalid city/district/dong parent or area code' USING ERRCODE='23514';
  END IF;
 END IF;
 IF TG_OP='UPDATE' AND EXISTS (
  SELECT 1 FROM ref_admin_area child WHERE child.parent_area_id=OLD.area_id AND
  (NOT ((NEW.area_level='CITY' AND child.area_level='DISTRICT') OR (NEW.area_level='DISTRICT' AND child.area_level='DONG'))
   OR child.code_system<>NEW.code_system OR child.area_code NOT LIKE NEW.area_code||'%')
 ) THEN RAISE EXCEPTION 'Area edit would invalidate children' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER area_hierarchy BEFORE INSERT OR UPDATE ON spotfit.ref_admin_area
FOR EACH ROW EXECUTE FUNCTION spotfit.guard_area_hierarchy();

