CREATE FUNCTION spotfit.guard_neighborhood_score() RETURNS trigger LANGUAGE plpgsql
SET search_path = spotfit, public, pg_catalog AS $$
DECLARE c service_safety_prediction; t service_safety_prediction; p service_scoring_policy;
BEGIN
 SELECT * INTO STRICT c FROM service_safety_prediction WHERE safety_prediction_id=NEW.crime_prediction_id;
 SELECT * INTO STRICT t FROM service_safety_prediction WHERE safety_prediction_id=NEW.traffic_prediction_id;
 SELECT * INTO STRICT p FROM service_scoring_policy WHERE scoring_policy_id=NEW.scoring_policy_id;
 IF c.safety_domain<>'CRIME_EXPOSURE' OR t.safety_domain<>'TRAFFIC_ACCIDENT'
   OR c.area_id<>NEW.area_id OR t.area_id<>NEW.area_id
   OR NEW.reference_year<>c.reference_year OR NEW.prediction_year<>c.prediction_year
   OR NEW.crime_score<>c.safety_score OR NEW.traffic_score<>t.safety_score
   OR NEW.total_score<>round(c.safety_score*p.crime_weight+t.safety_score*p.traffic_weight,4)
   OR NOT EXISTS (SELECT 1 FROM service_grade_policy WHERE scoring_policy_id=p.scoring_policy_id AND grade=NEW.total_grade AND NEW.total_rank BETWEEN minimum_rank AND maximum_rank) THEN
  RAISE EXCEPTION 'Score area, component, weighted total, year or grade mismatch' USING ERRCODE='23514';
 END IF;
 -- Traffic may be a 2025 reference while crime targets 2027/2028; retain both FKs.
 RETURN NEW;
END $$;
CREATE TRIGGER neighborhood_score_guard BEFORE INSERT OR UPDATE ON spotfit.service_neighborhood_score
FOR EACH ROW EXECUTE FUNCTION spotfit.guard_neighborhood_score();

CREATE FUNCTION spotfit.guard_recommendation_result() RETURNS trigger LANGUAGE plpgsql
SET search_path = spotfit, public, pg_catalog AS $$
DECLARE q service_recommendation_request; p service_property_prediction; s service_neighborhood_score;
        policy service_recommendation_policy; parent_id bigint; expected numeric;
BEGIN
 SELECT * INTO STRICT q FROM service_recommendation_request WHERE request_id=NEW.request_id FOR UPDATE;
 SELECT * INTO STRICT policy FROM service_recommendation_policy WHERE recommendation_policy_id=q.recommendation_policy_id;
 SELECT * INTO STRICT p FROM service_property_prediction WHERE property_prediction_id=NEW.property_prediction_id;
 SELECT * INTO STRICT s FROM service_neighborhood_score WHERE neighborhood_score_id=NEW.neighborhood_score_id;
 SELECT parent_area_id INTO parent_id FROM ref_admin_area WHERE area_id=NEW.area_id AND area_level='DONG';
 expected:=CASE WHEN q.preferred_area_sqm IS NULL THEN p.predicted_amount ELSE round(p.predicted_price_per_sqm*q.preferred_area_sqm,4) END;
 IF parent_id IS NULL OR parent_id<>s.area_id OR p.area_id<>NEW.area_id
  OR p.transaction_type<>q.transaction_type OR s.prediction_year<>q.crime_prediction_year
  OR NEW.recommendation_rank>policy.recommendation_count OR expected IS NULL OR NEW.predicted_amount<>expected
  OR NEW.predicted_amount NOT BETWEEN q.minimum_budget AND q.maximum_budget
  OR NEW.neighborhood_score<>s.total_score OR NEW.neighborhood_grade<>s.total_grade THEN
   RAISE EXCEPTION 'Recommendation price, budget, region, rank, year or score mismatch' USING ERRCODE='23514';
 END IF;
 IF policy.one_dong_per_district AND EXISTS (
  SELECT 1 FROM service_recommendation_result r JOIN ref_admin_area a USING(area_id)
  WHERE r.request_id=NEW.request_id AND a.parent_area_id=parent_id
    AND (TG_OP='INSERT' OR (r.request_id,r.recommendation_rank)<>(OLD.request_id,OLD.recommendation_rank))
 ) THEN RAISE EXCEPTION 'Only one recommended dong per district is allowed' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER recommendation_result_guard BEFORE INSERT OR UPDATE ON spotfit.service_recommendation_result
FOR EACH ROW EXECUTE FUNCTION spotfit.guard_recommendation_result();

