"""Mechanically export the checked-in 2026-10 MOIS codes/geometry to SQL.

No network access. No invented borough/dong names. Output is a self-contained
SQL seed, so executing it on Ubuntu/Windows needs only psql, not Python.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'frontend/public/seoul-dong.geojson'
REGISTRY=ROOT/'backend/app/data/admin_boundary_registry.json'
DEST=ROOT/'infra/postgres/migrations/003_seoul_area_seed.sql'

def literal(value):
    return "'"+str(value).replace("'","''")+"'"

def main():
    raw=SOURCE.read_bytes()
    geo=json.loads(raw.decode('utf-8-sig'))
    registry=json.loads(REGISTRY.read_text(encoding='utf-8-sig'))
    assert registry['effective_from']=='2026-10-01'
    features=geo['features']
    assert len(features)==registry['neighborhood_count']==427
    districts={};rows=[];seen=set()
    for f in features:
        p=f['properties'];code=p['adm_cd2'];gu=p['sgg'];name=p['adm_nm']
        assert re.fullmatch(r'11\d{8}',code) and re.fullmatch(r'11\d{3}',gu)
        assert code.startswith(gu) and code not in seen
        seen.add(code)
        assert name.startswith('서울특별시 '+p['sggnm']+' ')
        districts[gu]=p['sggnm']
        dong=name.split(' ',2)[2]
        assert f['geometry']['type'] in ('Polygon','MultiPolygon')
        rows.append((code,gu,dong,json.dumps(f['geometry'],ensure_ascii=False,separators=(',',':'))))
    assert len(districts)==registry['district_count']==25
    sql=["-- GENERATED by scripts/build_postgres_area_seed.py; do not hand edit.",
         '-- Source: frontend/public/seoul-dong.geojson (SGIS / vuski/admdongkor; KOGL Type 1 / CC BY 4.0).',
         '-- Source SHA256: '+hashlib.sha256(raw).hexdigest(),
         '-- MOIS adm_cd2, NOT the eight-digit SGIS adm_cd. 1 city + 25 districts + 427 dongs.',
         '-- valid_from is the known snapshot date, not the original date of administrative creation.',
         '-- Normalize to valid MultiPolygon EPSG:4326; repeated installs never overwrite rows.',
         "INSERT INTO spotfit.ref_admin_area(area_code,area_name,area_level,valid_from,source_snapshot) VALUES ('11','서울특별시','CITY','2026-10-01','seoul-admin-2026-10') ON CONFLICT (code_system,area_code,valid_from) DO NOTHING;",
         'INSERT INTO spotfit.ref_admin_area(area_code,area_name,area_level,parent_area_id,valid_from,source_snapshot)',
         "SELECT d.code,d.name,'DISTRICT',p.area_id,'2026-10-01','seoul-admin-2026-10' FROM (VALUES",
         ',\n'.join('('+literal(c)+','+literal(n)+')' for c,n in sorted(districts.items())),
         ") d(code,name) CROSS JOIN spotfit.ref_admin_area p WHERE p.area_code='11' AND p.code_system='MOIS' AND p.valid_from='2026-10-01'",
         'ON CONFLICT (code_system,area_code,valid_from) DO NOTHING;']
    for code,gu,dong,geometry in sorted(rows):
        sql.extend([
          'INSERT INTO spotfit.ref_admin_area(area_code,area_name,area_level,parent_area_id,valid_from,boundary,source_snapshot)',
          f"SELECT {literal(code)},{literal(dong)},'DONG',p.area_id,'2026-10-01',",
          f"ST_Multi(ST_CollectionExtract(ST_MakeValid(ST_SetSRID(ST_GeomFromGeoJSON({literal(geometry)}),4326)),3)),'seoul-admin-2026-10'",
          f"FROM spotfit.ref_admin_area p WHERE p.code_system='MOIS' AND p.area_code={literal(gu)} AND p.valid_from='2026-10-01'",
          'ON CONFLICT (code_system,area_code,valid_from) DO NOTHING;'])
    sql.extend([
      '-- Parent geometry is derived from the SAME dong snapshot, not an older gu file.',
      'UPDATE spotfit.ref_admin_area p SET boundary=b.geometry FROM (',
      ' SELECT parent_area_id,ST_Multi(ST_CollectionExtract(ST_UnaryUnion(ST_Collect(boundary)),3)) AS geometry',
      " FROM spotfit.ref_admin_area WHERE area_level='DONG' AND valid_from='2026-10-01' AND code_system='MOIS' GROUP BY parent_area_id",
      ') b WHERE p.area_id=b.parent_area_id AND p.boundary IS NULL;',
      'UPDATE spotfit.ref_admin_area p SET boundary=b.geometry FROM (',
      ' SELECT parent_area_id,ST_Multi(ST_CollectionExtract(ST_UnaryUnion(ST_Collect(boundary)),3)) AS geometry',
      " FROM spotfit.ref_admin_area WHERE area_level='DISTRICT' AND valid_from='2026-10-01' AND code_system='MOIS' GROUP BY parent_area_id",
      ') b WHERE p.area_id=b.parent_area_id AND p.boundary IS NULL;',
      'INSERT INTO spotfit.ref_admin_area_alias(area_id,alias_name,valid_from)',
      "SELECT area_id,replace(area_name,'제',''),valid_from FROM spotfit.ref_admin_area",
      "WHERE area_level='DONG' AND valid_from='2026-10-01' AND area_name ~ '제[0-9]' AND code_system='MOIS'",
      'ON CONFLICT(area_id,alias_name,valid_from) DO NOTHING;',
    ])
    DEST.write_text('\n'.join(sql)+'\n',encoding='utf-8')
    print(f'{DEST}: 453 areas, 427 source geometries, {DEST.stat().st_size:,} bytes')

if __name__=='__main__':main()
